/**
 * ─────────────────────────────────────────────────────────────────────────────
 *  DOCUMENTARY CONFIG — the single place to change topic, look, timing & audio.
 * ─────────────────────────────────────────────────────────────────────────────
 *
 *  • meta        → title, resolution, fps
 *  • theme       → colours + fonts (the whole design system reads from here)
 *  • features    → toggle subtitles, grain, vignette, letterbox, debug labels
 *  • audio       → music / ambience / voice-over / sfx levels and ducking
 *  • scenes      → ORDER, DURATION, TRANSITION and NARRATION of every scene
 *
 *  Scene *content* (dates, stats, chart data, quotes) lives in ./content.ts and
 *  replaceable media lives in ./assets.ts.
 *
 *  Timing model: scenes play back-to-back; each scene's `transitionOut`
 *  overlaps it with the next scene by `frames`. The total duration is computed
 *  automatically in utils/timing.ts — never hard-code it elsewhere.
 */

export type TransitionType =
  | 'crossfade'
  | 'dipToBlack'
  | 'whipPan'
  | 'lightLeak'
  | 'shapeWipe'
  | 'zoomThrough'
  | 'blurDissolve'
  | 'iris';

export type SfxName = 'whoosh' | 'impact' | 'riser' | 'alarm' | 'beep' | 'rumble';

/** A narration line. Times are seconds relative to the start of its scene. */
export type NarrationCue = {
  start: number;
  end: number;
  text: string;
};

export type SceneId =
  | 'opening'
  | 'introduction'
  | 'history'
  | 'machine'
  | 'journey'
  | 'descent'
  | 'data'
  | 'analysis'
  | 'conclusion'
  | 'credits';

export type SceneConfig = {
  id: SceneId;
  title: string;
  /** Why this scene exists in the story — documentation for editors. */
  purpose: string;
  durationSec: number;
  transitionOut?: {type: TransitionType; frames: number};
  /**
   * Narration script. Shown as subtitles and used for music ducking.
   * When a voice-over file exists, keep these cues aligned with it.
   */
  narration: NarrationCue[];
  /**
   * If true, the scene renders its own on-screen text for the narration
   * (e.g. kinetic typography in the opening) so the subtitle track skips it.
   */
  narrationIsOnScreen?: boolean;
  /** Optional per-scene voice-over file in /public (e.g. 'audio/vo/opening.mp3'). */
  voiceOver?: string | null;
  /** Sound effects, seconds relative to the scene start. */
  sfx?: {at: number; name: SfxName; volume?: number}[];
};

